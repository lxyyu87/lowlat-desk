use winit::keyboard::KeyCode;

/// Map a physical key (the same codes winit reports on macOS and Windows)
/// to a Windows virtual-key code for `SendInput`.
pub fn keycode_to_vk(code: KeyCode) -> Option<u16> {
    Some(match code {
        KeyCode::Backquote => 0xC0,
        KeyCode::Backslash => 0xDC,
        KeyCode::BracketLeft => 0xDB,
        KeyCode::BracketRight => 0xDD,
        KeyCode::Comma => 0xBC,
        KeyCode::Digit0 => 0x30,
        KeyCode::Digit1 => 0x31,
        KeyCode::Digit2 => 0x32,
        KeyCode::Digit3 => 0x33,
        KeyCode::Digit4 => 0x34,
        KeyCode::Digit5 => 0x35,
        KeyCode::Digit6 => 0x36,
        KeyCode::Digit7 => 0x37,
        KeyCode::Digit8 => 0x38,
        KeyCode::Digit9 => 0x39,
        KeyCode::Equal => 0xBB,
        KeyCode::IntlBackslash => 0xE2,
        KeyCode::KeyA => 0x41,
        KeyCode::KeyB => 0x42,
        KeyCode::KeyC => 0x43,
        KeyCode::KeyD => 0x44,
        KeyCode::KeyE => 0x45,
        KeyCode::KeyF => 0x46,
        KeyCode::KeyG => 0x47,
        KeyCode::KeyH => 0x48,
        KeyCode::KeyI => 0x49,
        KeyCode::KeyJ => 0x4A,
        KeyCode::KeyK => 0x4B,
        KeyCode::KeyL => 0x4C,
        KeyCode::KeyM => 0x4D,
        KeyCode::KeyN => 0x4E,
        KeyCode::KeyO => 0x4F,
        KeyCode::KeyP => 0x50,
        KeyCode::KeyQ => 0x51,
        KeyCode::KeyR => 0x52,
        KeyCode::KeyS => 0x53,
        KeyCode::KeyT => 0x54,
        KeyCode::KeyU => 0x55,
        KeyCode::KeyV => 0x56,
        KeyCode::KeyW => 0x57,
        KeyCode::KeyX => 0x58,
        KeyCode::KeyY => 0x59,
        KeyCode::KeyZ => 0x5A,
        KeyCode::Minus => 0xBD,
        KeyCode::Period => 0xBE,
        KeyCode::Quote => 0xDE,
        KeyCode::Semicolon => 0xBA,
        KeyCode::Slash => 0xBF,
        KeyCode::AltLeft => 0xA4,
        KeyCode::AltRight => 0xA5,
        KeyCode::Backspace => 0x08,
        KeyCode::CapsLock => 0x14,
        KeyCode::ControlLeft => 0xA2,
        KeyCode::ControlRight => 0xA3,
        KeyCode::Delete => 0x2E,
        KeyCode::ArrowDown => 0x28,
        KeyCode::End => 0x23,
        KeyCode::Enter => 0x0D,
        KeyCode::Escape => 0x1B,
        KeyCode::F1 => 0x70,
        KeyCode::F2 => 0x71,
        KeyCode::F3 => 0x72,
        KeyCode::F4 => 0x73,
        KeyCode::F5 => 0x74,
        KeyCode::F6 => 0x75,
        KeyCode::F7 => 0x76,
        KeyCode::F8 => 0x77,
        KeyCode::F9 => 0x78,
        KeyCode::F10 => 0x79,
        KeyCode::F11 => 0x7A,
        KeyCode::F12 => 0x7B,
        KeyCode::Home => 0x24,
        KeyCode::Insert => 0x2D,
        KeyCode::ArrowLeft => 0x25,
        KeyCode::SuperLeft => 0x5B,
        KeyCode::SuperRight => 0x5C,
        KeyCode::PageDown => 0x22,
        KeyCode::PageUp => 0x21,
        KeyCode::ArrowRight => 0x27,
        KeyCode::ShiftLeft => 0xA0,
        KeyCode::ShiftRight => 0xA1,
        KeyCode::Space => 0x20,
        KeyCode::Tab => 0x09,
        KeyCode::ArrowUp => 0x26,
        KeyCode::Numpad0 => 0x60,
        KeyCode::Numpad1 => 0x61,
        KeyCode::Numpad2 => 0x62,
        KeyCode::Numpad3 => 0x63,
        KeyCode::Numpad4 => 0x64,
        KeyCode::Numpad5 => 0x65,
        KeyCode::Numpad6 => 0x66,
        KeyCode::Numpad7 => 0x67,
        KeyCode::Numpad8 => 0x68,
        KeyCode::Numpad9 => 0x69,
        KeyCode::NumpadAdd => 0x6B,
        KeyCode::NumpadSubtract => 0x6D,
        KeyCode::NumpadMultiply => 0x6A,
        KeyCode::NumpadDivide => 0x6F,
        KeyCode::NumpadDecimal => 0x6E,
        KeyCode::NumpadEnter => 0x0D,
        _ => return None,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn letters_digits_and_arrows_use_windows_virtual_keys() {
        assert_eq!(keycode_to_vk(KeyCode::KeyA), Some(0x41));
        assert_eq!(keycode_to_vk(KeyCode::Digit1), Some(0x31));
        assert_eq!(keycode_to_vk(KeyCode::ArrowLeft), Some(0x25));
        assert_eq!(keycode_to_vk(KeyCode::SuperLeft), Some(0x5B));
    }
}
